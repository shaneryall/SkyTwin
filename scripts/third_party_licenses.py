r"""Write the licence notices of every crate linked into Skytwin's command and Python package.

    python3 scripts/third_party_licenses.py           # writes crates/skytwin-py/THIRD-PARTY-LICENSES.txt
    python3 scripts/third_party_licenses.py --check   # exit 1 if that file is out of date

The crates are those `cargo tree -e normal,no-proc-macro` lists for `skytwin-cli` and
`skytwin-py`: everything compiled into the binary and the wheel, without the procedural macros
and build tools that only run at compile time. Each crate's licence comes from `cargo metadata`,
and its text from the licence files shipped in the crate's source. Where a crate offers a choice
(`MIT OR Apache-2.0`), Skytwin takes it under MIT. The Python wheel carries the result, as its
`license-files` entry in `crates/skytwin-py/pyproject.toml` asks. A crate under Skytwin's own
licence, GPL-3.0-or-later, points to Skytwin's LICENSE instead of repeating it.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates/skytwin-py/THIRD-PARTY-LICENSES.txt"
PACKAGES = ("skytwin-cli", "skytwin-py")
PREFERRED = ("MIT", "Apache-2.0", "BSD-3-Clause", "BSD-2-Clause", "ISC", "Zlib", "Unicode-3.0", "GPL-3.0-or-later")
FILE_HINTS = {
    "MIT": ("LICENSE-MIT", "LICENSE.MIT", "LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING"),
    "Apache-2.0": ("LICENSE-APACHE", "LICENSE.APACHE", "LICENSE", "LICENSE.txt", "LICENSE.md"),
}


def cargo(*args):
    """Output of `cargo` with `args`, run at the repository root."""
    return subprocess.run(["cargo", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def linked():
    """(name, version) of every non-workspace crate linked into the packages, sorted."""
    found = set()
    for pkg in PACKAGES:
        tree = cargo("tree", "--locked", "-p", pkg, "-e", "normal,no-proc-macro", "--prefix", "none", "-f", "{p}")
        for line in tree.splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[1].startswith("v"):
                found.add((parts[0], parts[1][1:]))
    workspace = {(p["name"], p["version"]) for p in metadata()["packages"] if p["source"] is None}
    return sorted(found - workspace)


_META = None


def metadata():
    """`cargo metadata` for the workspace, read once."""
    global _META
    if _META is None:
        _META = json.loads(cargo("metadata", "--locked", "--format-version", "1"))
    return _META


def chosen(expression):
    """The licence Skytwin takes from an SPDX `expression`: the first of PREFERRED it offers."""
    options = [t.strip("() ") for t in expression.replace("/", " OR ").split(" OR ")]
    for want in PREFERRED:
        if want in options:
            return want
    return options[0]


def text(directory, licence):
    """The text of `licence` among the licence files in `directory`."""
    names = [p.name for p in directory.iterdir() if p.is_file()]
    for hint in FILE_HINTS.get(licence, ()):
        if hint in names:
            return (directory / hint).read_text(errors="replace").strip()
    files = sorted(n for n in names if n.upper().startswith(("LICENSE", "LICENCE", "COPYING")))
    if not files:
        raise SystemExit(f"no licence file in {directory}")
    return "\n\n".join((directory / n).read_text(errors="replace").strip() for n in files)


def render():
    """The notices file as text."""
    by_key = {(p["name"], p["version"]): p for p in metadata()["packages"]}
    out = [
        "Third-party licences",
        "",
        "Skytwin's command (skytwin-cli) and Python package (skytwin) are GPL-3.0-or-later. They",
        "include the following crates, each under the licence named, whose notices follow.",
        "Generated by scripts/third_party_licenses.py from Cargo.lock; do not edit by hand.",
        "",
    ]
    sections = []
    for name, version in linked():
        p = by_key[(name, version)]
        expression = p["license"] or "unknown"
        licence = chosen(expression)
        out.append(f"  {name} {version}: {licence}" + (f" (offered: {expression})" if expression != licence else ""))
        if licence == "GPL-3.0-or-later":
            body = "The GNU General Public License, version 3 or later: the same text as Skytwin's LICENSE."
        else:
            body = text(Path(p["manifest_path"]).parent, licence)
        notice = Path(p["manifest_path"]).parent / "NOTICE"
        if notice.is_file():
            body += "\n\nNOTICE\n\n" + notice.read_text(errors="replace").strip()
        rule = "=" * 78
        sections.append(f"{rule}\n{name} {version} ({licence})\n{p.get('repository') or ''}\n{rule}\n\n{body}\n")
    return "\n".join(out) + "\n\n" + "\n".join(sections)


def main(argv):
    """Write the notices file, or with `--check` report whether it is current."""
    new = render()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text() != new:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 scripts/third_party_licenses.py")
            return 1
        return 0
    OUT.write_text(new)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(linked())} crates")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
